"""Serialise the reconstruction to the human-readable geometry spec.

The YAML is a RENDERING of ``demo_map.geometry``, never an input to it: the
derivation lives in code, the spec is what you read.  ``tests/demo_map`` asserts
the file on disk still matches what the code derives, so the two cannot drift.
"""

from __future__ import annotations

from pathlib import Path

from .geometry import (CHOSEN, HEIGHT, LABELLED, THICKNESS, DemoMap,
                       build_demo_map, remeasure)
from .route import Route, build_reference_route

SPEC_PATH = Path("docs/demo_maps/demo_map_geometry.yaml")

_HEADER = """\
# Metric geometry of the measured demo room.
#
# GENERATED by `python3 -m demo_map.export` (src/demo_map/export.py) from
# src/demo_map/geometry.py.  Edit the module, not this file; tests/demo_map
# fails if the two disagree.
#
# Source drawing : docs/demo_maps/measured_map.jpg  (blue numbers = tape
#                  measurements in cm; the drawing is NOT to scale, so no
#                  coordinate here is taken from its pixels)
# Route sketch   : docs/demo_maps/desired_route.jpg (topology only)
# Units          : metres.  Floor at z = 0.
#
# FRAME
#   origin  west end of curved feature C1's chord, ON the room-side face of the
#           long wall -- the first tick of the drawing's dimension chain and the
#           only unambiguous datum on that wall
#   +x      east, along the long wall, the direction of travel from START
#   +y      north, up out of the lower corridor toward the upper room
#           (so the long wall's room-side face IS the line y = 0)
#
# CONVENTION
#   Wall p0/p1 lie on the ROOM-SIDE FACE, because that is what a tape measure
#   spans.  `inward` is the unit normal from that face into the free space; the
#   slab is extruded `thickness` the other way.  MuJoCo box geoms sit on the
#   resulting centreline -- see demo_map/mapv3.py and demo_map/mujoco_scene.py.
"""


class _Pair(list):
    """An x/y pair, dumped inline so the spec reads as coordinates."""


def _f(x: float) -> float:
    return round(float(x), 6)


def _p(p) -> _Pair:
    return _Pair([_f(p[0]), _f(p[1])])


def spec_dict(m: DemoMap | None = None, r: Route | None = None) -> dict:
    m = m or build_demo_map()
    r = r or build_reference_route(m)
    return {
        "meta": {
            "name": "demo_room",
            "units": "m",
            "wall_thickness_m": THICKNESS,
            "wall_height_m": HEIGHT,
            "source_drawing": "docs/demo_maps/measured_map.jpg",
            "route_sketch": "docs/demo_maps/desired_route.jpg",
            "frame": ("origin = C1 west chord end on the long wall's room-side "
                      "face; +x east along that wall; +y north; floor z=0"),
            "point_convention": "wall p0/p1 are ROOM-SIDE FACE points",
        },
        "labelled_dimensions_cm": {
            k: _f(v * 100.0) for k, v in LABELLED.items()
        },
        "underdetermined": {
            k: {"value_m": v["value"], "what": v["what"],
                "sketch_suggests": v["sketch_says"], "why_this_value": v["why"]}
            for k, v in CHOSEN.items()
        },
        "derived_points_m": {k: _f(v) for k, v in m.key_points.items()},
        "walls": [
            {"id": w.wid, "p0": _p(w.p0), "p1": _p(w.p1),
             "inward": _p(w.inward), "length_m": _f(w.length),
             "thickness_m": w.thickness, "height_m": w.height,
             "centreline": [_p(w.centreline[0]), _p(w.centreline[1])],
             "source": w.source, "note": w.note}
            for w in m.walls
        ],
        "curved_features": [
            {"id": c.cid, "kind": "circular arc from chord + sagitta",
             "center": _p(c.center), "radius_m": _f(c.radius),
             "chord_p0": _p(c.chord0), "chord_p1": _p(c.chord1),
             "chord_len_m": _f(c.chord_len), "proud_m": _f(c.proud),
             "height_m": c.height, "source": c.source, "note": c.note}
            for c in m.curves
        ],
        "openings": [
            {"id": o.oid, "kind": o.kind, "p0": _p(o.p0), "p1": _p(o.p1),
             "width_m": _f(o.width), "source": o.source}
            for o in m.openings
        ],
        "free_space_rects": [_Pair([_f(v) for v in rc]) for rc in m.rooms],
        "regions": {
            "start": {"center": _p(m.start.center), "radius_m": m.start.radius,
                      "heading_rad": m.start.heading_rad, "note": m.start.note},
            "goal": {"center": _p(m.goal.center), "radius_m": m.goal.radius,
                     "heading_rad": m.goal.heading_rad, "note": m.goal.note},
        },
        "reference_route": {
            "total_length_m": _f(r.length),
            "waypoints": [{"id": wid, "xy": _p(p)} for wid, p in r.waypoints()],
            "segments": [
                {"id": s.sid, "kind": s.kind, "p0": _p(s.p0), "p1": _p(s.p1),
                 "length_m": _f(s.length), "follows": s.follows,
                 "hand": s.hand, "note": s.note,
                 **({"arc": {"center": _p(s.center), "radius_m": _f(s.radius),
                             "ccw": bool(s.ccw)}} if s.is_arc else {})}
                for s in r.segs
            ],
        },
        "validation": {
            "labelled_dimension_check": [
                {"feature": d["feature"], "labelled_m": _f(d["labelled"]),
                 "reconstructed_m": _f(d["recon"]),
                 "abs_error_m": float(f"{abs(d['labelled'] - d['recon']):.3e}"),
                 "measured_how": d["how"]}
                for d in remeasure(m)
            ],
        },
    }


def dump_yaml(m: DemoMap | None = None, r: Route | None = None) -> str:
    """The spec body as YAML text.  Shared by the writer and the drift test, so
    the test compares against exactly what would be written."""
    import yaml

    class _Dumper(yaml.SafeDumper):
        pass

    _Dumper.add_representer(_Pair, lambda d, x: d.represent_sequence(
        "tag:yaml.org,2002:seq", list(x), flow_style=True))

    return yaml.dump(spec_dict(m, r), Dumper=_Dumper, sort_keys=False, width=94,
                     default_flow_style=False, allow_unicode=True)


def write_yaml(path: Path | str = SPEC_PATH, m: DemoMap | None = None,
               r: Route | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_HEADER + "\n" + dump_yaml(m, r))
    return path


if __name__ == "__main__":
    print("wrote", write_yaml())
